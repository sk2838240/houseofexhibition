<script>
    (function () {
        const track = document.getElementById('eventsTrack');
        const prevBtn = document.getElementById('eventsPrev');
        const nextBtn = document.getElementById('eventsNext');
        const viewport = document.getElementById('eventsCarousel');

        if (!track || !prevBtn || !nextBtn) return;

        const originalCards = Array.from(track.children);
        const total = originalCards.length;

        let perView = getPerView();
        let index = 0;
        let cardStep = 0;
        let autoplayTimer = null;
        let isAnimating = false;

        function getPerView() {
            if (window.innerWidth <= 575) return 1;
            if (window.innerWidth <= 991) return 2;
            return 3;
        }

        function buildClones() {
            track.querySelectorAll('.event-card.clone').forEach(el => el.remove());

            // Prepend clones of the last `perView` cards
            for (let i = total - perView; i < total; i++) {
                const clone = originalCards[i].cloneNode(true);
                clone.classList.add('clone');
                track.insertBefore(clone, track.firstChild);
            }
            // Append clones of the first `perView` cards
            for (let i = 0; i < perView; i++) {
                const clone = originalCards[i].cloneNode(true);
                clone.classList.add('clone');
                track.appendChild(clone);
            }

            index = perView;
            measure();
            setPosition(false);
        }

        function measure() {
            const card = track.querySelector('.event-card');
            if (!card) return;
            const rect = card.getBoundingClientRect();
            const style = getComputedStyle(card);
            const marginRight = parseFloat(style.marginRight) || 0;
            cardStep = rect.width + marginRight;
        }

        function setPosition(animate) {
            track.style.transition = animate ? 'transform 0.5s ease' : 'none';
            track.style.transform = `translateX(${-index * cardStep}px)`;
        }

        function goTo(newIndex) {
            if (isAnimating) return;
            isAnimating = true;
            index = newIndex;
            setPosition(true);
        }

        function next() {
            goTo(index + 1);
        }

        function prev() {
            goTo(index - 1);
        }

        track.addEventListener('transitionend', () => {
            isAnimating = false;
            const maxIndex = perView + total; // first clone-of-start position
            if (index >= maxIndex) {
                index -= total;
                setPosition(false);
            } else if (index < perView) {
                index += total;
                setPosition(false);
            }
        });

        nextBtn.addEventListener('click', () => {
            resetAutoplay();
            next();
        });

        prevBtn.addEventListener('click', () => {
            resetAutoplay();
            prev();
        });

        function startAutoplay() {
            autoplayTimer = setInterval(next, 4000);
        }

        function stopAutoplay() {
            clearInterval(autoplayTimer);
        }

        function resetAutoplay() {
            stopAutoplay();
            startAutoplay();
        }

        if (viewport) {
            viewport.addEventListener('mouseenter', stopAutoplay);
            viewport.addEventListener('mouseleave', startAutoplay);
        }

        // Basic touch/swipe support
        let touchStartX = 0;
        let touchDeltaX = 0;

        track.addEventListener('touchstart', (e) => {
            touchStartX = e.touches[0].clientX;
            stopAutoplay();
        }, { passive: true });

        track.addEventListener('touchmove', (e) => {
            touchDeltaX = e.touches[0].clientX - touchStartX;
        }, { passive: true });

        track.addEventListener('touchend', () => {
            if (Math.abs(touchDeltaX) > 40) {
                touchDeltaX < 0 ? next() : prev();
            }
            touchDeltaX = 0;
            startAutoplay();
        });

        let resizeTimer;
        window.addEventListener('resize', () => {
            clearTimeout(resizeTimer);
            resizeTimer = setTimeout(() => {
                const newPerView = getPerView();
                if (newPerView !== perView) {
                    perView = newPerView;
                    buildClones();
                } else {
                    measure();
                    setPosition(false);
                }
            }, 150);
        });

        buildClones();
        startAutoplay();
    })();
</script>
